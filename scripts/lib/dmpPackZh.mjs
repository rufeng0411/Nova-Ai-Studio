/**
 * @param {string} tail slug without mkt-dmp- prefix
 */
export function dmpTailToZh(tail) {
  if (!tail) return '';
  if (TAIL_ZH[tail]) return TAIL_ZH[tail];
  const parts = tail.split('-').filter(Boolean);
  const translated = parts.map((part) => WORD_ZH[part]).filter(Boolean);
  if (translated.length >= 2) return translated.slice(-3).join('').slice(0, 9);
  if (translated.length === 1) return translated[0];
  return '';
}
