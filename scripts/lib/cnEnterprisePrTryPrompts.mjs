/**
 * @param {string} title
 * @param {string} doing
 * @param {string[]} fills
 * @param {string} prepare
 * @param {string} get
 * @param {string|string[]} deliver
 */
function build(title, doing, fills, prepare, get, deliver) {
  const list = Array.isArray(deliver) ? deliver : [deliver];
  const must = list.join('、');
  return [
    title,
    '',
    `【你在做什么】${doing}`,
    '',
    '【请填写】（不知道就写「不清楚」或「按常见中小微假设」，不要空着）',
    ...fills,
    '',
    `【请准备】${prepare}`,
    '',
    `【你会得到】${get}`,
    '',
    `须交付：${must}。`,
    '写入系统分配任务目录。',
    DISCLAIMER,
  ].join('\n');
}

