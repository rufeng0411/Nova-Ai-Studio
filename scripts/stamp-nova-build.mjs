#!/usr/bin/env node
/**
 * PD-SAAS-FORK: Stamp Nova product build id (UTC timestamp) before UI production builds / pack.
 * Output: ui/src/saas/brand/productBuild.generated.ts
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../ui/src/saas/brand/productBuild.generated.ts');

function formatBuildId(date = new Date()) {
  const pad = (n) => String(n).padStart(2, '0');
  return `${date.getUTCFullYear()}${pad(date.getUTCMonth() + 1)}${pad(date.getUTCDate())}-${pad(date.getUTCHours())}${pad(date.getUTCMinutes())}${pad(date.getUTCSeconds())}`;
}

const buildId = process.env.NOVA_PRODUCT_BUILD?.trim() || formatBuildId();
const content = `/** Auto-generated by scripts/stamp-nova-build.mjs — do not edit */\nexport const NOVA_PRODUCT_BUILD = '${buildId}';\n`;

writeFileSync(OUT, content, 'utf8');
console.log(`[stamp-nova-build] NOVA_PRODUCT_BUILD=${buildId}`);
